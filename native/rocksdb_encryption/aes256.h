// Self-contained AES-256 block cipher (FIPS-197), single 16-byte block
// encrypt/decrypt only — no mode of operation (ECB/CBC/CTR) is implemented
// here on purpose. RocksDB's CTREncryptionProvider (see shim.cc) already
// builds its own CTR keystream by calling BlockCipher::Encrypt once per
// counter block; a second mode-of-operation layer here would be redundant
// and error-prone to keep in sync with RocksDB's own counter/IV handling.
//
// Not a vendored third-party library — written directly against FIPS-197
// (Advanced Encryption Standard, NIST, 2001) so CareGraph's encryption-at-rest
// path (Rule 8) has no undisclosed dependency. Key size is fixed at 256 bits
// (Nk=8, Nr=14) to match CAREGRAPH_ENCRYPTION_KEY's 32-byte requirement.
//
// This header only needs to be *correct* against the FIPS-197 test vectors
// (verified in shim_test.cc) — it does not need to be fast; RocksDB's CTR
// mode calls this once per 16-byte block, not per byte.
#pragma once

