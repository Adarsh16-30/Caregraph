// AES-256: 14 rounds, 60-word (240-byte) expanded key schedule.
class Aes256 {
 public:
  static constexpr size_t kKeyBytes = 32;
  static constexpr size_t kBlockBytes = 16;
  static constexpr int kNr = 14;   // rounds
  static constexpr int kNk = 8;    // key words (32-bit)

  explicit Aes256(const uint8_t key[kKeyBytes]) { KeyExpansion(key); }

  void EncryptBlock(uint8_t block[kBlockBytes]) const {
    uint8_t state[4][4];
    ToState(block, state);
    AddRoundKey(state, 0);
    for (int round = 1; round < kNr; ++round) {
      SubBytes(state);
      ShiftRows(state);
      MixColumns(state);
      AddRoundKey(state, round);
    }
    SubBytes(state);
    ShiftRows(state);
    AddRoundKey(state, kNr);
    FromState(state, block);
  }

  void DecryptBlock(uint8_t block[kBlockBytes]) const {
    uint8_t state[4][4];
    ToState(block, state);
    AddRoundKey(state, kNr);
    for (int round = kNr - 1; round >= 1; --round) {
      InvShiftRows(state);
      InvSubBytes(state);
      AddRoundKey(state, round);
      InvMixColumns(state);
    }
    InvShiftRows(state);
    InvSubBytes(state);
    AddRoundKey(state, 0);
    FromState(state, block);
  }

 private:
  // round_key_ holds (Nr+1) round keys of 16 bytes each = 240 bytes total.
  uint8_t round_key_[(kNr + 1) * kBlockBytes];

  void KeyExpansion(const uint8_t key[kKeyBytes]) {
    uint8_t* rk = round_key_;
    std::memcpy(rk, key, kKeyBytes);

    uint8_t temp[4];
    int words_total = 4 * (kNr + 1);
    static const uint8_t kRcon[] = {0x01, 0x02, 0x04, 0x08, 0x10,
                                     0x20, 0x40, 0x80, 0x1b, 0x36};
    for (int i = kNk; i < words_total; ++i) {
      std::memcpy(temp, rk + 4 * (i - 1), 4);
      if (i % kNk == 0) {
        // RotWord
        uint8_t t = temp[0];
        temp[0] = temp[1];
        temp[1] = temp[2];
        temp[2] = temp[3];
        temp[3] = t;
        // SubWord
        for (int j = 0; j < 4; ++j) temp[j] = detail::kSBox[temp[j]];
        temp[0] = static_cast<uint8_t>(temp[0] ^ kRcon[i / kNk - 1]);
      } else if (i % kNk == 4) {
        for (int j = 0; j < 4; ++j) temp[j] = detail::kSBox[temp[j]];
      }
      for (int j = 0; j < 4; ++j) {
        rk[4 * i + j] = static_cast<uint8_t>(rk[4 * (i - kNk) + j] ^ temp[j]);
      }
    }
  }

  static void ToState(const uint8_t in[16], uint8_t state[4][4]) {
    for (int c = 0; c < 4; ++c)
      for (int r = 0; r < 4; ++r) state[r][c] = in[c * 4 + r];
  }

  static void FromState(const uint8_t state[4][4], uint8_t out[16]) {
    for (int c = 0; c < 4; ++c)
      for (int r = 0; r < 4; ++r) out[c * 4 + r] = state[r][c];
  }

  void AddRoundKey(uint8_t state[4][4], int round) const {
    const uint8_t* rk = round_key_ + round * kBlockBytes;
    for (int c = 0; c < 4; ++c)
      for (int r = 0; r < 4; ++r) state[r][c] ^= rk[c * 4 + r];
  }

  static void SubBytes(uint8_t state[4][4]) {
    for (int r = 0; r < 4; ++r)
      for (int c = 0; c < 4; ++c) state[r][c] = detail::kSBox[state[r][c]];
  }

  static void InvSubBytes(uint8_t state[4][4]) {
    for (int r = 0; r < 4; ++r)
      for (int c = 0; c < 4; ++c) state[r][c] = detail::kInvSBox[state[r][c]];
  }

  static void ShiftRows(uint8_t state[4][4]) {
    uint8_t t;
    // row 1: shift left 1
    t = state[1][0];
    state[1][0] = state[1][1];
    state[1][1] = state[1][2];
    state[1][2] = state[1][3];
    state[1][3] = t;
    // row 2: shift left 2
    t = state[2][0];
    state[2][0] = state[2][2];
    state[2][2] = t;
    t = state[2][1];
    state[2][1] = state[2][3];
    state[2][3] = t;
    // row 3: shift left 3 (== shift right 1)
    t = state[3][3];
    state[3][3] = state[3][2];
    state[3][2] = state[3][1];
    state[3][1] = state[3][0];
    state[3][0] = t;
  }

  static void InvShiftRows(uint8_t state[4][4]) {
    uint8_t t;
    // row 1: shift right 1
    t = state[1][3];
    state[1][3] = state[1][2];
    state[1][2] = state[1][1];
    state[1][1] = state[1][0];
    state[1][0] = t;
    // row 2: shift right 2 (== shift left 2, self-inverse)
    t = state[2][0];
    state[2][0] = state[2][2];
    state[2][2] = t;
    t = state[2][1];
    state[2][1] = state[2][3];
    state[2][3] = t;
    // row 3: shift right 3 (== shift left 1)
    t = state[3][0];
    state[3][0] = state[3][1];
    state[3][1] = state[3][2];
    state[3][2] = state[3][3];
    state[3][3] = t;
  }

  static void MixColumns(uint8_t state[4][4]) {
    for (int c = 0; c < 4; ++c) {
      uint8_t a0 = state[0][c], a1 = state[1][c], a2 = state[2][c],
              a3 = state[3][c];
      state[0][c] = static_cast<uint8_t>(detail::XTime(a0) ^
                                          (detail::XTime(a1) ^ a1) ^ a2 ^ a3);
      state[1][c] = static_cast<uint8_t>(a0 ^ detail::XTime(a1) ^
                                          (detail::XTime(a2) ^ a2) ^ a3);
      state[2][c] = static_cast<uint8_t>(a0 ^ a1 ^ detail::XTime(a2) ^
                                          (detail::XTime(a3) ^ a3));
      state[3][c] = static_cast<uint8_t>((detail::XTime(a0) ^ a0) ^ a1 ^ a2 ^
                                          detail::XTime(a3));
    }
  }

  static void InvMixColumns(uint8_t state[4][4]) {
    for (int c = 0; c < 4; ++c) {
      uint8_t a0 = state[0][c], a1 = state[1][c], a2 = state[2][c],
              a3 = state[3][c];
      state[0][c] = static_cast<uint8_t>(
          detail::GMul(a0, 0x0e) ^ detail::GMul(a1, 0x0b) ^
          detail::GMul(a2, 0x0d) ^ detail::GMul(a3, 0x09));
      state[1][c] = static_cast<uint8_t>(
          detail::GMul(a0, 0x09) ^ detail::GMul(a1, 0x0e) ^
          detail::GMul(a2, 0x0b) ^ detail::GMul(a3, 0x0d));
      state[2][c] = static_cast<uint8_t>(
          detail::GMul(a0, 0x0d) ^ detail::GMul(a1, 0x09) ^
          detail::GMul(a2, 0x0e) ^ detail::GMul(a3, 0x0b));
      state[3][c] = static_cast<uint8_t>(
          detail::GMul(a0, 0x0b) ^ detail::GMul(a1, 0x0d) ^
          detail::GMul(a2, 0x09) ^ detail::GMul(a3, 0x0e));
    }
  }
};

